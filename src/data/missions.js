export const totalQuestions = missions.reduce((total, mission) => total + mission.questions.length, 0);

export function getRating(percentage) {
  if (percentage >= 90) return 'Эксперт цифровой безопасности';
  if (percentage >= 70) return 'Уверенный защитник';
  if (percentage >= 50) return 'Начинающий кибердетектив';
  return 'Требуется дополнительная тренировка';
}
